@pytest.hookimpl(hookwrapper=True)
def pytest_runtest_makereport(item, call):
    """Capture verification test failures and skips dynamically."""
    outcome = yield
    report = outcome.get_result()

    # Determine benchmark code from test function name or item attribute
    code = getattr(item, "_verification_code", None)
    if not code:
        name = item.name.lower()
        mapping = {
            "test_v1": "V1",
            "test_v2b": "V2b",
            "test_v2": "V2",
            "test_v3": "V3",
            "test_v4": "V4",
            "test_v5": "V5",
            "test_v6": "V6",
            "test_v7": "V7",
            "test_v8": "V8",
            "test_x1": "X1",
            "test_x2": "X2",
            "test_x3": "X3",
            "test_x4": "X4",
            "test_x5": "X5",
            "test_x6": "X6",
        }
        for prefix, c in mapping.items():
            if name.startswith(prefix):
                code = c
                break

    if code and code in VERIFICATION_REGISTRY:
        if report.when == "call" and report.failed:
            VERIFICATION_REGISTRY[code]["status"] = "failed"
            VERIFICATION_REGISTRY[code]["skip_reason"] = None
            VERIFICATION_REGISTRY[code]["skipped_reason"] = None
            if report.longrepr:
                lines = str(report.longrepr).splitlines()
                fail_summary = lines[-1] if lines else "AssertionError"
                VERIFICATION_REGISTRY[code]["measured_value"] = f"FAILED: {fail_summary}"
        elif report.skipped:
            VERIFICATION_REGISTRY[code]["status"] = "not_run"
            if isinstance(report.longrepr, tuple) and len(report.longrepr) >= 3:
                reason = str(report.longrepr[2])
                VERIFICATION_REGISTRY[code]["skip_reason"] = reason
                VERIFICATION_REGISTRY[code]["skipped_reason"] = reason


def pytest_sessionfinish(session, exitstatus):
    """Generate tests/results.json and web/public/data/test_results.json from the test run."""
    import os
    if os.environ.get("LIGHTPATH_MUTATION_CHECK") == "1":
        return

    # Only export if verification tests were part of the run
    executed_benchmarks = [v for v in VERIFICATION_REGISTRY.values() if v["status"] != "not_run" or "fixture absent" in str(v.get("skip_reason", ""))]
    if not executed_benchmarks:
        return

    primary_codes = ["V1", "V2", "V2b", "V3", "V4", "V5", "V6", "V7", "V8"]
    extra_codes = ["X1", "X2", "X3", "X4", "X5", "X6"]

    checks = [VERIFICATION_REGISTRY[c] for c in primary_codes if c in VERIFICATION_REGISTRY]
    extra_checks = [VERIFICATION_REGISTRY[c] for c in extra_codes if c in VERIFICATION_REGISTRY]

    all_items = checks + extra_checks
    total = len(all_items)
    passed = sum(1 for item in all_items if item["status"] == "passed")
    not_run = sum(1 for item in all_items if item["status"] == "not_run")
    failed = sum(1 for item in all_items if item["status"] == "failed")

    overall_status = "failed" if failed > 0 else "passed"

    # Charts data must strictly come from measurements recorded during test execution.
    # No hard-coded chart data is permitted (PROJECT_RULES.md Rule 2).
    # If a test did not run, its chart is not recorded and not drawn.
    charts = dict(CHARTS_DATA)

    results_data = {
        "status": overall_status,
        "counts": {
            "total": total,
            "passed": passed,
            "not_run": not_run,
            "skipped": not_run,
            "failed": failed,
        },
        "failures": [item["name"] for item in all_items if item["status"] == "failed"],
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "checks": checks,
        "extra_checks": extra_checks,
        "charts": charts,
    }

    results_path = root_dir / "tests" / "results.json"
    results_path.parent.mkdir(parents=True, exist_ok=True)
    with open(results_path, "w", encoding="utf-8") as f:
        json.dump(results_data, f, indent=2)

    web_data_path = root_dir / "web" / "public" / "data" / "test_results.json"
    if web_data_path.parent.exists():
        with open(web_data_path, "w", encoding="utf-8") as f:
            json.dump(results_data, f, indent=2)
