#!/usr/bin/env python3
"""Build SPICE meta-kernel (kernels/meta.tm) using relative paths.

Conforms to NAIF SPICE KEEPER specifications.
"""

import argparse
import json
import sys
from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parent.parent
KERNELS_DIR = ROOT_DIR / "kernels"
MANIFEST_PATH = KERNELS_DIR / "kernels.json"
META_KERNEL_PATH = KERNELS_DIR / "meta.tm"


def build_meta_kernel(output_path: Path = META_KERNEL_PATH) -> int:
    if not MANIFEST_PATH.exists():
        print(f"Error: Manifest not found at {MANIFEST_PATH}", file=sys.stderr)
        return 1

    with open(MANIFEST_PATH, "r", encoding="utf-8") as f:
        try:
            kernels = json.load(f)
        except json.JSONDecodeError as e:
            print(f"Error reading {MANIFEST_PATH}: {e}", file=sys.stderr)
            return 1

    kernel_rel_paths = []
    for item in kernels:
        local_path = item.get("local_path", "")
        if local_path:
            # Path relative to kernels/ directory
            p = Path(local_path)
            # If path starts with 'kernels/', strip it so it's relative to kernels/
            if p.parts and p.parts[0] == "kernels":
                rel = Path(*p.parts[1:])
            else:
                rel = p
            kernel_rel_paths.append(f"'$KERNELS/{rel.as_posix()}'")

    meta_content = (
        "KPL/MK\n\n"
        "\\begintext\n\n"
        "LightPath SPICE Meta-Kernel\n"
        "Automatically generated by scripts/make_meta_kernel.py\n\n"
        "The PATH_VALUES variable defines the directory containing the kernels\n"
        "relative to the location of this meta-kernel file.\n\n"
        "\\begindata\n\n"
        "PATH_VALUES  = ( '.' )\n"
        "PATH_SYMBOLS = ( 'KERNELS' )\n\n"
        "KERNELS_TO_LOAD = (\n"
        + ",\n".join(f"    {k}" for k in kernel_rel_paths)
        + "\n)\n\n"
        "\\begintext\n"
    )

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(meta_content)

    print(f"[OK] Generated SPICE meta-kernel at {output_path.relative_to(ROOT_DIR)}")
    print(f"     Included {len(kernel_rel_paths)} kernel references with relative paths.")
    return 0


def main():
    parser = argparse.ArgumentParser(description="Generate SPICE meta-kernel kernels/meta.tm")
    parser.add_argument("--output", type=Path, default=META_KERNEL_PATH, help="Output meta-kernel path")
    args = parser.parse_args()

    sys.exit(build_meta_kernel(args.output))


if __name__ == "__main__":
    main()
